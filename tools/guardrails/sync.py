from __future__ import annotations

from pathlib import Path
from typing import Any

from .architecture import (
    render_architecture_readme,
    render_dependency_cruiser,
    render_importlinter,
)
from .manual import Card, Chapter
from .util import (
    GuardrailsError,
    read_text,
    render_frontmatter,
    resolve_under,
    write_text,
)

GENERATED = "<!-- generated by guardrails; edit manual/ instead -->"
GENERATED_MARKER = "generated by guardrails"


def render_agents(card: Card, chapters: list[Chapter]) -> str:
    lines = [
        GENERATED,
        "",
        card.body.rstrip(),
        "",
        "## 章节索引",
        "",
        "| 章节 | 何时加载 | 不何时加载 |",
        "|---|---|---|",
    ]
    for chapter in sorted(chapters, key=lambda item: item.name):
        when = chapter.when_to_use[0] if chapter.when_to_use else ""
        when_not = chapter.when_not_to_use[0] if chapter.when_not_to_use else ""
        lines.append(f"| `{chapter.name}` | {when} | {when_not} |")
    lines.append("")
    lines.append("> 只加载 `guardrails brief` 选中的章节；不要一次读完所有章节。")
    return "\n".join(lines)


def render_claude_skill(chapter: Chapter) -> str:
    meta: dict[str, Any] = {
        "name": chapter.name,
        "description": chapter.description,
    }
    if chapter.meta.get("allowed-tools"):
        meta["allowed-tools"] = chapter.meta["allowed-tools"]
    return f"{GENERATED}\n\n" + render_frontmatter(meta) + "\n" + chapter.body.rstrip() + "\n"


def render_kiro(chapter: Chapter) -> str:
    meta: dict[str, Any] = {
        "inclusion": "auto",
        "name": chapter.name,
        "description": chapter.description,
    }
    return f"{GENERATED}\n\n" + render_frontmatter(meta) + "\n" + chapter.body.rstrip() + "\n"


def render_cursor(chapter: Chapter) -> str:
    meta: dict[str, Any] = {
        "description": chapter.description,
        "alwaysApply": False,
    }
    if chapter.globs:
        meta["globs"] = ", ".join(chapter.globs)
    return render_frontmatter(meta) + "\n" + f"{GENERATED}\n\n" + chapter.body.rstrip() + "\n"


def render_claude_md() -> str:
    return (
        f"{GENERATED}\n\n"
        "# CLAUDE.md\n\n"
        "先读 `AGENTS.md`。每个任务先跑 `guardrails brief --task specs/<id>`，"
        "只加载它选中的 1–3 个章节。不要一次读完 `manual/`。\n"
    )


def render_llms(card: Card, chapters: list[Chapter]) -> str:
    lines = [GENERATED, "", "# llms.txt", "", "- AGENTS.md", f"- {card.path.name}"]
    for chapter in sorted(chapters, key=lambda item: item.name):
        lines.append(f"- manual/chapters/{chapter.name}/SKILL.md")
    return "\n".join(lines) + "\n"


def sync_views(
    root: Path,
    config: dict[str, Any],
    check: bool = False,
    force: bool = False,
) -> dict[str, Any]:
    from .manual import load_card, load_chapters

    card = load_card(root, config)
    chapters = load_chapters(root, config)
    adapters = config.get("adapters", {})

    outputs: dict[Path, str] = {}
    outputs[resolve_under(root, adapters.get("agents", "AGENTS.md"))] = render_agents(card, chapters)

    claude_dir = resolve_under(root, adapters.get("claude", ".claude/skills"))
    kiro_dir = resolve_under(root, adapters.get("kiro", ".kiro/steering"))
    cursor_dir = resolve_under(root, adapters.get("cursor", ".cursor/rules"))

    for chapter in chapters:
        outputs[claude_dir / chapter.name / "SKILL.md"] = render_claude_skill(chapter)
        outputs[kiro_dir / f"{chapter.name}.md"] = render_kiro(chapter)
        outputs[cursor_dir / f"{chapter.name}.mdc"] = render_cursor(chapter)

    outputs[root / "CLAUDE.md"] = render_claude_md()
    outputs[root / "llms.txt"] = render_llms(card, chapters)

    languages = [str(item) for item in config.get("project", {}).get("languages", [])]
    arch_dir = root / ".guardrails"
    if any(item in {"typescript", "javascript"} for item in languages):
        outputs[arch_dir / "dependency-cruiser.js"] = render_dependency_cruiser(config)
    if "python" in languages:
        outputs[arch_dir / "importlinter.toml"] = render_importlinter(config)
    outputs[arch_dir / "README.md"] = render_architecture_readme(config)

    drift: list[dict[str, str]] = []
    written: list[str] = []
    conflicts: list[dict[str, str]] = []

    for path, content in outputs.items():
        current = read_text(path) if path.exists() else None
        if current is not None and GENERATED_MARKER not in current and not force:
            conflicts.append({"path": str(path), "status": "unmanaged"})
            continue
        current_norm = current.rstrip() + "\n" if current is not None else None
        content_norm = content.rstrip() + "\n"
        if current_norm != content_norm:
            drift.append({"path": str(path), "status": "missing" if current is None else "stale"})
            if not check:
                write_text(path, content)
                written.append(str(path))

    return {
        "written": written,
        "drift": drift,
        "conflicts": conflicts,
        "checked": check,
    }
