from __future__ import annotations

import re
from typing import Any


def _layer_paths(config: dict[str, Any]) -> dict[str, list[str]]:
    layers = [str(layer) for layer in config.get("layers", [])]
    result: dict[str, list[str]] = {layer: [] for layer in layers}
    for module in config.get("modules", []):
        layer = str(module.get("layer", ""))
        if layer in result:
            result[layer].append(str(module.get("path", "")).rstrip("/"))
    return result


def _regex(paths: list[str], fallback: str) -> str:
    values = paths or [fallback]
    return "|".join(re.escape(value) for value in values)


def render_dependency_cruiser(config: dict[str, Any]) -> str:
    layers = [str(layer) for layer in config.get("layers", [])]
    paths = _layer_paths(config)
    rules: list[str] = [
        '{ name: "no-circular", severity: "error", from: {}, to: { circular: true } }'
    ]
    for index, lower in enumerate(layers):
        for higher in layers[index + 1 :]:
            from_paths = _regex(paths.get(lower, []), f"modules/{lower}")
            to_paths = _regex(paths.get(higher, []), f"modules/{higher}")
            rules.append(
                "{ name: \"no-%s-to-%s\", severity: \"error\", "
                "from: { path: \"^(%s)/\" }, to: { path: \"^(%s)/\" } }"
                % (lower, higher, from_paths, to_paths)
            )
    rules.append(
        '{ name: "no-cross-module-internal", severity: "error", '
        'from: { path: "^modules/([^/]+)/" }, '
        'to: { path: "^modules/(?!$1)/", pathNot: "CONTRACT" } }'
    )
    return (
        "// generated by guardrails; edit guardrails.yaml instead\n"
        "module.exports = {\n"
        "  forbidden: [\n    "
        + ",\n    ".join(rules)
        + "\n  ],\n"
        "  options: { doNotFollow: { path: \"node_modules\" }, tsPreCompilationDeps: true },\n"
        "};\n"
    )


def render_importlinter(config: dict[str, Any]) -> str:
    root = str(config.get("project", {}).get("name", "app")).replace("-", "_")
    layers = [str(layer) for layer in config.get("layers", [])]
    ordered = [f"{root}.{layer}" for layer in reversed(layers)]
    values = ", ".join(f'"{item}"' for item in ordered)
    return (
        "# generated by guardrails; edit guardrails.yaml instead\n"
        "[tool.importlinter]\n"
        f'root_packages = ["{root}"]\n\n'
        "[[tool.importlinter.contracts]]\n"
        'name = "layers"\n'
        'type = "layers"\n'
        f"layers = [{values}]\n"
    )


def render_architecture_readme(config: dict[str, Any]) -> str:
    languages = [str(item) for item in config.get("project", {}).get("languages", [])]
    lines = [
        "<!-- generated by guardrails; edit guardrails.yaml instead -->",
        "",
        "# Architecture rules",
        "",
        "这些文件由 `guardrails sync` 从 `guardrails.yaml` 生成。",
        "",
    ]
    if any(item in {"typescript", "javascript"} for item in languages):
        lines += [
            "## TypeScript / JavaScript",
            "",
            "```bash",
            "npx depcruise --config .guardrails/dependency-cruiser.js src",
            "```",
            "",
        ]
    if "python" in languages:
        lines += [
            "## Python",
            "",
            "把 `.guardrails/importlinter.toml` 的 `[tool.importlinter]` 段合并到 `pyproject.toml`，然后运行：",
            "",
            "```bash",
            "lint-imports",
            "```",
            "",
        ]
    lines += [
        "## 规则",
        "",
        "- 层之间只允许从高到低依赖；反向依赖失败。",
        "- 禁止循环依赖。",
        "- 跨模块只能 import 对方的 `CONTRACT`，不能 import 内部文件。",
        "",
    ]
    return "\n".join(lines)
